import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { createServer } from "node:net";
import { basename, join } from "node:path";
import { rootDir } from "./helpers/vite-config.ts";

// Each slot owns ten consecutive host ports starting at PORT_BASE + slot * 10.
const PORT_BASE = 20000;
const SLOTS = 99;
const PORTS = {
	WP_HTTP_PORT: 0,
	WP_HTTPS_PORT: 1,
	PHPMYADMIN_PORT: 2,
	MAILPIT_PORT: 3,
	MAILPIT_SMTP_PORT: 4,
	XDEBUG_PORT: 5,
};

const force = process.argv.includes("--force");
const envFile = join(rootDir, ".env");

function git(...args: string[]) {
	return execFileSync("git", ["-C", rootDir, ...args], { encoding: "utf8" }).trim();
}

function readEnv(file: string, name: string) {
	if (!existsSync(file)) {
		return undefined;
	}

	return readFileSync(file, "utf8").match(new RegExp(`^${name}=(.+)$`, "m"))?.[1];
}

function readSlot(file: string) {
	const slot = readEnv(file, "WORKTREE_SLOT");

	return slot === undefined ? undefined : Number(slot);
}

// Feeds the URL column of `wt list` (`[list] url` in .config/wt.toml), which can only read
// Worktrunk's per-branch vars.
function recordUrl(url: string) {
	try {
		execFileSync("wt", ["-C", rootDir, "config", "state", "vars", "set", `wpurl=${url}`], {
			stdio: "ignore",
		});
	} catch {
		// Worktrunk is optional, and a detached HEAD has no branch to store the URL on.
	}
}

function isPortFree(port: number) {
	return new Promise<boolean>((resolve) => {
		const server = createServer()
			.once("error", () => resolve(false))
			.once("listening", () => server.close(() => resolve(true)))
			.listen(port, "0.0.0.0");
	});
}

async function isSlotFree(slot: number) {
	for (const offset of Object.values(PORTS)) {
		if (!(await isPortFree(PORT_BASE + slot * 10 + offset))) {
			return false;
		}
	}

	return true;
}

// The main checkout keeps the default ports and wordpress.localhost, which its database already uses.
if (git("rev-parse", "--git-dir") === git("rev-parse", "--git-common-dir") && !force) {
	console.log(
		"This is the main checkout; it runs on the default ports. Use --force to override.",
	);
	process.exit(0);
}

if (readSlot(envFile) !== undefined && !force) {
	recordUrl(readEnv(envFile, "WP_URL") ?? "");
	console.log(`.env already reserves slot ${readSlot(envFile)}. Use --force to pick a new one.`);
	process.exit(0);
}

const takenSlots = new Set(
	git("worktree", "list", "--porcelain")
		.split("\n")
		.filter((line) => line.startsWith("worktree "))
		.map((line) => line.slice("worktree ".length))
		.filter((path) => path !== rootDir)
		.map((path) => readSlot(join(path, ".env"))),
);

// Starting from a hash of the path keeps worktrees created at the same time from probing the same slot.
const start = createHash("sha1").update(rootDir).digest().readUInt32BE(0) % SLOTS;
let slot: number | undefined;

for (let i = 0; i < SLOTS; i++) {
	const candidate = ((start + i) % SLOTS) + 1;

	if (!takenSlots.has(candidate) && (await isSlotFree(candidate))) {
		slot = candidate;
		break;
	}
}

if (slot === undefined) {
	console.error("No free port slot left; remove unused worktrees or stop their stacks.");
	process.exit(1);
}

const ports = Object.fromEntries(
	Object.entries(PORTS).map(([name, offset]) => [name, PORT_BASE + slot * 10 + offset]),
);
const project = basename(rootDir)
	.toLowerCase()
	.replace(/[^a-z0-9_-]+/g, "-");

writeFileSync(
	envFile,
	[
		"# Generated by `pnpm worktree:env`. WordPress stores WP_URL in its database, so keep these ports",
		"# once `pnpm run setup` has run.",
		`WORKTREE_SLOT=${slot}`,
		`COMPOSE_PROJECT_NAME=${project}`,
		`WP_URL=http://localhost:${ports.WP_HTTP_PORT}`,
		...Object.entries(ports).map(([name, port]) => `${name}=${port}`),
		"# Set to debug and point .vscode/launch.json at XDEBUG_PORT to step through this worktree.",
		"XDEBUG_MODE=off",
		"",
	].join("\n"),
);

recordUrl(`http://localhost:${ports.WP_HTTP_PORT}`);

console.log(`Reserved slot ${slot} for ${project}:`);
console.log(`  WordPress   http://localhost:${ports.WP_HTTP_PORT}`);
console.log(`  phpMyAdmin  http://localhost:${ports.PHPMYADMIN_PORT}`);
console.log(`  Mailpit     http://localhost:${ports.MAILPIT_PORT}`);
